#!/usr/bin/env python3
"""Write docs/register_map.md from the register map and the entity names.

    .venv/bin/python tools/gen_docs.py            # rewrite it
    .venv/bin/python tools/gen_docs.py --check    # exit 1 if it is stale

registers.py is loaded on its own, without the integration package (and so
without Home Assistant): it imports nothing but the standard library.
"""

from __future__ import annotations

import argparse
import importlib.util
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "docs" / "register_map.md"
sys.path.insert(0, str(ROOT / "tools"))

from gen_translations import COIL, DISCRETE, HOLDING, SENSOR  # noqa: E402


def _registers():
    path = ROOT / "custom_components" / "daikin_fwecsa_modbus" / "registers.py"
    spec = importlib.util.spec_from_file_location("fwecsa_registers", path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module  # dataclasses look the module up by name
    spec.loader.exec_module(module)
    return module


HEADINGS = {
    "coil": ("Coils", "FC1 read, FC15 write. Read-only as a binary sensor; a switch with "
             "*Allow writes* on."),
    "discrete": ("Discrete inputs", "FC2, read-only."),
    "holding": ("Holding registers", "FC3 read, FC16 write. Read-only as a sensor; a number "
                "(the fan speed: a select) with *Allow writes* on."),
    "input": ("Input registers", "FC4, read-only."),
}


def _entities(reg, prefix: str) -> str:
    key, table = reg.key, str(reg.table)
    if table == "coil":
        ids = [f"switch.{prefix}_{key}", f"binary_sensor.{prefix}_{key}"]
    elif table == "discrete":
        ids = [f"binary_sensor.{prefix}_{key}"]
    elif table == "holding":
        writable = "select" if key == "fan_speed" else "number"
        ids = [f"sensor.{prefix}_{key}", f"{writable}.{prefix}_{key}"]
    else:
        ids = [f"sensor.{prefix}_{key}"]
    return "<br>".join(f"`{i}`" for i in ids)


def _encoding(reg, enums) -> str:
    if reg.table.bits:
        return "0/1"
    if reg.key in enums:
        return ", ".join(f"{raw} {name}" for raw, name in enums[reg.key].items())
    if reg.scale != 1.0:
        return f"×{reg.scale:g} °C, signed"
    return "% (whole numbers, unverified)"


def render(prefix: str = "fancoil") -> str:
    module = _registers()
    names = {**COIL, **DISCRETE, **HOLDING, **SENSOR}
    lines = [
        "# FWECSA register map",
        "",
        "Generated by `tools/gen_docs.py` from `registers.py`; do not edit by hand.",
        "",
        "Source: Daikin *FWECSA Installation and operation manual*, FC66003946 Rev 00, "
        "NETWORKS AND CONNECTIVITY. The manual numbers each table from 1; the Modbus "
        "address is that number minus one. Scales and the meaning of the two-way flags are "
        "not in the manual: see the docstring of `registers.py` for what was measured and "
        "what is assumed.",
        "",
        f"Entity ids assume the default prefix `{prefix}`. The climate entity "
        f"`climate.{prefix}` is built from several of these.",
    ]
    for table in module.Table:
        title, note = HEADINGS[str(table)]
        lines += ["", f"## {title}", "", note, "",
                  "| No. | Addr | Manual | Name | Encoding | Entities |",
                  "|---:|---:|---|---|---|---|"]
        for reg in (r for r in module.REGISTERS if r.table is table):
            name = names[reg.key][0]
            lines.append(f"| {reg.number} | {reg.address} | {reg.manual} | {name} | "
                         f"{_encoding(reg, module.ENUMS)} | {_entities(reg, prefix)} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the file is stale")
    args = parser.parse_args()
    text = render()
    if OUTPUT.exists() and OUTPUT.read_text(encoding="utf-8") == text:
        return 0
    if args.check:
        print(f"stale: {OUTPUT.relative_to(ROOT)}")
        return 1
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote: {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
